"""Public demonstration accounts ("NASA Evaluator Access").

These three accounts are intentionally PUBLIC: their credentials are shown on the login page so that
evaluators, teachers and NASA Space Apps reviewers can try every role. They are separate from the
private bootstrap accounts (ADMIN_EMAIL / ADMIN_PASSWORD ... generated by Render), which are never shown.

Safety limits for demo accounts (enforced in the backend, see `demo_forbidden`):
- cannot create, edit or delete users or change roles (user management is read-only);
- cannot change their own password (would lock out other evaluators);
- cannot delete the seeded synthetic baseline data (they can delete records they create);
- e-mail addresses of non-demo users and IP addresses in the audit log are masked for them.
"""
from flask import abort
from flask_login import current_user

from .extensions import db

DEMO_ACCOUNTS = (
    {"role": "admin", "label": "ADMINISTRADOR", "label_en": "Administrator",
     "email": "admin.demo@astravital.example", "password": "AstraDemo-Admin-2026",
     "full_name": "Demo Administrador (cuenta pública)",
     "can": "Todo el sistema: CRUD de astronautas, misiones y mediciones, alertas, reportes, auditoría. Usuarios solo lectura."},
    {"role": "doctor", "label": "MÉDICO / ESPECIALISTA", "label_en": "Doctor / Specialist",
     "email": "medico.demo@astravital.example", "password": "AstraDemo-Medico-2026",
     "full_name": "Demo Médico (cuenta pública)",
     "can": "Registrar y editar mediciones, revisar y resolver alertas, reportes. Sin gestión de astronautas ni usuarios."},
    {"role": "operator", "label": "OPERADOR", "label_en": "Operator",
     "email": "operador.demo@astravital.example", "password": "AstraDemo-Operador-2026",
     "full_name": "Demo Operador (cuenta pública)",
     "can": "Consultar el sistema y registrar mediciones. Sin edición, eliminación ni revisión de alertas."},
)
DEMO_EMAILS = {a["email"] for a in DEMO_ACCOUNTS}


def ensure_demo_accounts():
    """Idempotent: create the demo accounts if missing; otherwise restore role, status and public password.

    Returns (created, repaired). Running it any number of times never creates duplicates
    (users.email is UNIQUE and the lookup is by e-mail)."""
    from .models import User
    created = repaired = 0
    for acc in DEMO_ACCOUNTS:
        u = User.query.filter_by(email=acc["email"]).first()
        if u is None:
            u = User(email=acc["email"], full_name=acc["full_name"], role=acc["role"], is_demo=True, is_active_account=True)
            u.set_password(acc["password"])
            db.session.add(u)
            created += 1
            continue
        changed = False
        if u.role != acc["role"] or not u.is_active_account or not u.is_demo:
            u.role, u.is_active_account, u.is_demo = acc["role"], True, True
            changed = True
        if not u.check_password(acc["password"]):
            u.set_password(acc["password"])
            changed = True
        repaired += changed
    db.session.commit()
    return created, repaired


def is_demo_user(user=None):
    u = user or current_user
    return bool(getattr(u, "is_authenticated", False) and getattr(u, "is_demo", False))


def demo_forbidden(message):
    """Abort with 403 when the signed-in user is a public demo account."""
    if is_demo_user():
        abort(403, description=message)


def mask_email(email):
    """Mask an e-mail for demo viewers unless it belongs to a public demo account."""
    if not email or not is_demo_user() or email in DEMO_EMAILS:
        return email
    name, _, domain = email.partition("@")
    return f"{name[:1]}•••@{domain[:1]}•••"
